-- Execute uma vez no usuário Oracle usado pelo aplicativo.
-- Identificadores UUID permitem sincronizar novamente sem duplicar medições.
CREATE TABLE AGROPERDAS_MEDICOES (
    ID                 VARCHAR2(36 CHAR) PRIMARY KEY,
    DATA_COLHEITA      DATE NOT NULL,
    TALHAO             VARCHAR2(100 CHAR) NOT NULL,
    AREA_COLHIDA_HA    NUMBER(18, 4) NOT NULL,
    AREA_AMOSTRADA_M2  NUMBER(18, 4) NOT NULL,
    RESIDUO_AMOSTRA_KG NUMBER(18, 4) NOT NULL,
    MASSA_COLHIDA_T    NUMBER(18, 4) NOT NULL,
    LIMITE_PERCENTUAL  NUMBER(8, 4) NOT NULL,
    PERDA_ESTIMADA_T   NUMBER(18, 4) NOT NULL,
    PERCENTUAL_PERDA   NUMBER(8, 4) NOT NULL,
    CRIADO_EM          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_AGRO_AREA CHECK (AREA_COLHIDA_HA > 0 AND AREA_AMOSTRADA_M2 > 0),
    CONSTRAINT CK_AGRO_MASSA CHECK (MASSA_COLHIDA_T > 0 AND RESIDUO_AMOSTRA_KG >= 0),
    CONSTRAINT CK_AGRO_LIMITE CHECK (LIMITE_PERCENTUAL > 0 AND LIMITE_PERCENTUAL < 100)
);
